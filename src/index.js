function setupGeneralIpcHandlers() {
    ipcMain.handle('get-app-version', async () => {
        return app.getVersion();
    });

    ipcMain.handle('quit-application', async event => {
        try {
            stopMacOSAudioCapture();
            app.quit();
            return { success: true };
        } catch (error) {
            console.error('Error quitting application:', error);
            return { success: false, error: error.message };
        }
    });

    ipcMain.handle('open-external', async (event, url) => {
        try {
            await shell.openExternal(url);
            return { success: true };
        } catch (error) {
            console.error('Error opening external URL:', error);
            return { success: false, error: error.message };
        }
    });

    ipcMain.handle('toggle-click-through', () => {
        if (!mainWindow || mainWindow.isDestroyed()) return { success: false };
        // Toggle click through
        const isIgnored = mainWindow.isIgnoreMouseEvents ? !mainWindow.isIgnoreMouseEvents() : true;
        mainWindow.setIgnoreMouseEvents(isIgnored, { forward: true });
        mainWindow.webContents.send('click-through-toggled', isIgnored);
        return { success: true, isClickThrough: isIgnored };
    });

    // Debug logging from renderer
    ipcMain.on('log-message', (event, msg) => {
        console.log(msg);
    });
}

function setupExamIpcHandlers() {
    ipcMain.handle('exam:solve', async (event, options) => {
        try {
            return await solveCurrentExamQuestion(mainWindow, options);
        } catch (error) {
            console.error('Error in exam:solve IPC handler:', error);
            return { success: false, error: error.message };
        }
    });

    ipcMain.handle('exam:set-tray-answer', (event, letter, summary) => {
        setTrayAnswer(letter, summary);
        return { success: true };
    });

    ipcMain.handle('exam:clear-tray-answer', () => {
        setTrayAnswer(null);
        return { success: true };
    });

    ipcMain.handle('exam:update-mouse-trigger', (event, enabled, duration) => {
        if (enabled) {
            startClickHoldMonitor(duration || 5, () => {
                solveCurrentExamQuestion(mainWindow);
            });
        } else {
            stopClickHoldMonitor();
        }
        return { success: true };
    });

    ipcMain.handle('exam:trigger-screen-pulse', (event, count, color) => {
        const { triggerFullscreenPulse } = require('./utils/screenPulse');
        triggerFullscreenPulse(count || 2, color || '#facc15');
        return { success: true };
    });

    ipcMain.handle('exam:refresh-tray-icon', () => {
        const { refreshTrayIcon } = require('./utils/tray');
        refreshTrayIcon();
        return { success: true };
    });
}
