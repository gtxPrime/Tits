if (require('electron-squirrel-startup')) {
    process.exit(0);
}

const { app, BrowserWindow, shell, ipcMain } = require('electron');

// Enable DevTools remote debugging port for diagnostic inspection
app.commandLine.appendSwitch('remote-debugging-port', '9222');
const { createWindow, updateGlobalShortcuts } = require('./utils/window');
const { setupGeminiIpcHandlers, stopMacOSAudioCapture, sendToRenderer } = require('./utils/gemini');
const { initTray, setTrayAnswer, destroyTray } = require('./utils/tray');
const { startClickHoldMonitor, stopClickHoldMonitor } = require('./utils/mouseTrigger');
const { solveCurrentExamQuestion } = require('./utils/examSolver');
const storage = require('./storage');

const geminiSessionRef = { current: null };
let mainWindow = null;

function createMainWindow() {
    mainWindow = createWindow(sendToRenderer, geminiSessionRef);
    return mainWindow;
}

app.whenReady().then(async () => {
    // Initialize storage (checks version, resets if needed)
    storage.initializeStorage();

    // Trigger screen recording permission prompt on macOS if not already granted
    if (process.platform === 'darwin') {
        const { desktopCapturer } = require('electron');
        desktopCapturer.getSources({ types: ['screen'] }).catch(() => {});
    }

    createMainWindow();
    initTray(mainWindow, () => solveCurrentExamQuestion(mainWindow));

    try {
        setupGeminiIpcHandlers(geminiSessionRef);
    } catch (e) {
        console.error('Failed to setup Gemini IPC handlers:', e);
    }
    try {
        setupStorageIpcHandlers();
    } catch (e) {
        console.error('Failed to setup Storage IPC handlers:', e);
    }
    try {
        setupGeneralIpcHandlers();
    } catch (e) {
        console.error('Failed to setup General IPC handlers:', e);
    }
    try {
        setupExamIpcHandlers();
    } catch (e) {
        console.error('Failed to setup Exam IPC handlers:', e);
    }
});

app.on('window-all-closed', () => {
    stopMacOSAudioCapture();
    if (process.platform !== 'darwin') {
        app.quit();
    }
});

app.on('before-quit', () => {
    stopMacOSAudioCapture();
    stopClickHoldMonitor();
    try {
        const { destroyPulseWindow } = require('./utils/screenPulse');
        destroyPulseWindow();
    } catch (e) {}
    destroyTray();
    try {
        require('./utils/localai').closeLocalSession();
    } catch (e) {}
});

app.on('activate', () => {
    if (BrowserWindow.getAllWindows().length === 0) {
        createMainWindow();
    }
});

